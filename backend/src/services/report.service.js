  /**
   * 5. SLA Compliance PDF Generator
   */
  static generateSlaPdf({ activeVulns, breachedVulns, warningVulns, slaHoursByPriority }, user, res) {
    const doc = new PDFDocument({ margin: 40, size: 'A4', bufferPages: true });
    doc.pipe(res);

    const generationDate = ReportService.fmtDate(new Date());

    // Header Banner
    doc.rect(40, 40, doc.page.width - 80, 54).fill('#0f172a');
    doc.fillColor('#38bdf8').fontSize(18).font('Helvetica-Bold').text('FLAWTRACK', 55, 48);
    doc.fillColor('#94a3b8').fontSize(9).font('Helvetica').text('SLA Compliance & Remediation Timeliness Audit', 55, 70);

    doc.fillColor('#f8fafc').fontSize(11).font('Helvetica-Bold').text('SLA COMPLIANCE AUDIT', doc.page.width - 200, 48, { align: 'right' });
    doc.fillColor('#94a3b8').fontSize(8).font('Helvetica').text(`Date: ${generationDate}`, doc.page.width - 200, 64, { align: 'right' });
    doc.fillColor('#94a3b8').fontSize(8).font('Helvetica').text(`Generated by: ${user.name}`, doc.page.width - 200, 75, { align: 'right' });

    doc.y = 110;

    // SLA Target Hours by Priority Tier Table
    doc.fillColor('#0f172a').fontSize(11).font('Helvetica-Bold').text('Contractual SLA Targets by Priority Tier', 40, doc.y);
    doc.y += 10;

    doc.rect(40, doc.y, doc.page.width - 80, 18).fill('#f1f5f9');
    doc.fillColor('#334155').fontSize(8.5).font('Helvetica-Bold');
    doc.text('Priority Tier', 50, doc.y + 5);
    doc.text('Maximum Allowed Remediation Window', 160, doc.y + 5);
    doc.text('SLA Warning Threshold (75%)', 360, doc.y + 5);
    doc.y += 18;

    const targets = [
      { p: 'P1 - Critical', hrs: `${slaHoursByPriority.P1 || 24} hours (1 day)`, warn: `${(slaHoursByPriority.P1 || 24) * 0.75} hours` },
      { p: 'P2 - High', hrs: `${slaHoursByPriority.P2 || 72} hours (3 days)`, warn: `${(slaHoursByPriority.P2 || 72) * 0.75} hours` },
      { p: 'P3 - Medium', hrs: `${slaHoursByPriority.P3 || 168} hours (7 days)`, warn: `${(slaHoursByPriority.P3 || 168) * 0.75} hours` },
      { p: 'P4 - Low', hrs: `${slaHoursByPriority.P4 || 720} hours (30 days)`, warn: `${(slaHoursByPriority.P4 || 720) * 0.75} hours` },
    ];

    targets.forEach((t) => {
      doc.rect(40, doc.y, doc.page.width - 80, 18).strokeColor('#e2e8f0').stroke();
      doc.fillColor('#0f172a').fontSize(8.5).font('Helvetica').text(t.p, 50, doc.y + 5);
      doc.text(t.hrs, 160, doc.y + 5);
      doc.text(t.warn, 360, doc.y + 5);
      doc.y += 18;
    });

    doc.y += 16;

    // Current Status Metrics
    const totalActive = activeVulns.length;
    const totalBreached = breachedVulns.length;
    const totalWarning = warningVulns.length;
    const complianceRate = totalActive > 0 ? Math.round(((totalActive - totalBreached) / totalActive) * 100) : 100;

    doc.fillColor('#0f172a').fontSize(11).font('Helvetica-Bold').text('Current Remediation Pipeline Health', 40, doc.y);
    doc.y += 10;

    doc.fillColor('#334155').fontSize(9).font('Helvetica').text(
      `Active Work Items: ${totalActive}  |  Breached: ${totalBreached}  |  At-Risk (>75% window elapsed): ${totalWarning}  |  Compliance: ${complianceRate}%`,
      45,
      doc.y
    );
    doc.y += 20;

    // Overdue Breached Items Table
    doc.fillColor('#dc2626').fontSize(11).font('Helvetica-Bold').text('Breached Vulnerabilities (Overdue)', 40, doc.y);
    doc.y += 10;

    if (breachedVulns.length === 0) {
      doc.fillColor('#16a34a').fontSize(9).font('Helvetica').text('No breached vulnerabilities currently in the system. All items comply with SLA.', 45, doc.y);
      doc.y += 20;
    } else {
      doc.rect(40, doc.y, doc.page.width - 80, 18).fill('#dc2626');
      doc.fillColor('#ffffff').fontSize(8).font('Helvetica-Bold');
      doc.text('Priority', 45, doc.y + 5);
      doc.text('Title', 100, doc.y + 5);
      doc.text('Assigned To', 300, doc.y + 5);
      doc.text('SLA Deadline', 420, doc.y + 5);
      doc.y += 18;

      breachedVulns.slice(0, 15).forEach((v) => {
        doc.rect(40, doc.y, doc.page.width - 80, 18).strokeColor('#e2e8f0').stroke();
        doc.fillColor('#dc2626').fontSize(8).font('Helvetica-Bold').text(v.risk?.priority || 'P3', 45, doc.y + 5);
        doc.fillColor('#0f172a').font('Helvetica').text((v.title || '').slice(0, 35), 100, doc.y + 5);
        doc.text(v.assignedTo?.name || 'Unassigned', 300, doc.y + 5);
        doc.fillColor('#dc2626').text(ReportService.fmtDate(v.sla?.dueAt), 420, doc.y + 5);
        doc.y += 18;
      });
      doc.y += 16;
    }

    // Page Numbering
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      doc.rect(40, doc.page.height - 35, doc.page.width - 80, 0.5).fill('#cbd5e1');
      doc.fillColor('#64748b').fontSize(7.5).font('Helvetica').text(
        `FlawTrack Security Platform  |  CONFIDENTIAL - SLA AUDIT REPORT  |  Page ${i + 1} of ${range.count}`,
        40,
        doc.page.height - 25,
        { align: 'center', width: doc.page.width - 80 }
      );
    }

    doc.end();
  }

